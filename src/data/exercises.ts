const BY_ID = new Map<string, Exercise>(EXERCISES.map((e) => [e.id, e]));

export function getExercise(id: string): Exercise {
  const found = BY_ID.get(id);
  if (!found) throw new Error(`Unknown exercise id: ${id}`);
  return found;
}

export function findExercise(id: string): Exercise | undefined {
  return BY_ID.get(id);
}

export function exercisesByPattern(pattern: MovementPattern): Exercise[] {
  return EXERCISES.filter((e) => e.pattern === pattern);
}

