import type {
  Equipment,
  Exercise,
  ExperienceLevel,
  Goal,
  Muscle,
  MovementPattern,
  Orientation,
  ProgressionMethod,
  RestrictionTag,
} from '../domain/types';

/**
 * Default anterior/posterior classification per movement pattern (spec 17/18).
 * Individual exercises may override it.
 */
const PATTERN_ORIENTATION: Record<MovementPattern, Orientation> = {
  squat: 'anterior',
  lunge: 'anterior',
  step_up: 'anterior',
  hinge: 'posterior',
  knee_flexion: 'posterior',
  hip_extension: 'posterior',
  calf_raise: 'posterior',
  horizontal_push: 'anterior',
  vertical_push: 'anterior',
  horizontal_pull: 'posterior',
  vertical_pull: 'posterior',
  shoulder_isolation: 'neutral',
  arm_flexion: 'anterior',
  arm_extension: 'posterior',
  anti_extension: 'anterior',
  flexion: 'anterior',
  anti_rotation: 'neutral',
  anti_lateral_flexion: 'neutral',
  rotation: 'neutral',
};

interface ExerciseSeed {
  id: string;
  name: string;
  pattern: MovementPattern;
  primary: Muscle[];
  secondary?: Muscle[];
  orientation?: Orientation;
  requires?: Equipment[];
  anyOf?: Equipment[];
  level?: ExperienceLevel;
  difficulty?: number;
  stability?: number;
  joints?: Exercise['jointDemands'];
  reps?: [number, number];
  sets?: number;
  goals?: Partial<Record<Goal, number>>;
  fatigue?: number;
  tags?: RestrictionTag[];
  subs?: string[];
  progression?: ProgressionMethod;
  unilateral?: boolean;
  compound?: boolean;
  cue?: string;
}

function def(seed: ExerciseSeed): Exercise {
  const compound = seed.compound ?? true;
  return {
    id: seed.id,
    name: seed.name,
    primaryMuscles: seed.primary,
    secondaryMuscles: seed.secondary ?? [],
    pattern: seed.pattern,
    orientation: seed.orientation ?? PATTERN_ORIENTATION[seed.pattern],
    requires: seed.requires ?? [],
    anyOf: seed.anyOf ?? [],
    minExperience: seed.level ?? 'beginner',
    difficulty: seed.difficulty ?? (compound ? 3 : 2),
    stability: seed.stability ?? (compound ? 3 : 2),
    jointDemands: seed.joints ?? [],
    repRange: { min: seed.reps?.[0] ?? (compound ? 6 : 10), max: seed.reps?.[1] ?? (compound ? 10 : 15) },
    defaultSets: seed.sets ?? 3,
    goalSuitability: seed.goals ?? {},
    fatigueRating: seed.fatigue ?? (compound ? 3 : 1),
    restrictionTags: seed.tags ?? [],
    substitutions: seed.subs ?? [],
    progression: seed.progression ?? 'double_progression',
    unilateral: seed.unilateral ?? false,
    compound,
    cue: seed.cue,
  };
}

